import { expect, test } from 'claude-code/testing'

import { addProfile, findProfile, listProfile, parse, readKeys, setProfileKeys } from './jsonc'

const GUID = '{61c54bbd-c2c6-5271-96e7-009a87ff44bf}'

// shaped like the file Windows Terminal writes on first run: comments, a list, defaults
const SRC = `\uFEFF// This file was initially generated by Windows Terminal
{
    "$schema": "https://aka.ms/terminal-profiles-schema",
    "defaultProfile": "${GUID}",
    "profiles":
    {
        "defaults":
        {
            // Put settings here that you want to apply to all profiles.
        },
        "list":
        [
            {
                // Make changes here to the powershell.exe profile.
                "guid": "${GUID}",
                "name": "Windows PowerShell",
                "commandline": "powershell.exe", /* inline */
                "hidden": false
            },
            {
                "guid": "{0caa0dad-35be-5f56-a8ff-afceeeaa6101}",
                "name": "Command Prompt",
                "hidden": false
            }
        ]
    }
}
`

const target = (src: string, guid?: string) => findProfile(parse(src), guid)!

test('sets keys on the tab profile, keeping every comment and the other profiles', async () => {
  const out = setProfileKeys(SRC, GUID, { backgroundImage: 'C:\\sky\\night-idle.gif', backgroundImageOpacity: 0.75 })!
  expect(out).toContain('// Make changes here to the powershell.exe profile.')
  expect(out).toContain('/* inline */')
  expect(out).toContain('// Put settings here that you want to apply to all profiles.')
  expect(readKeys(target(out, GUID), ['backgroundImage', 'backgroundImageOpacity'])).toEqual({
    backgroundImage: 'C:\\sky\\night-idle.gif',
    backgroundImageOpacity: 0.75,
  })
  // the other profile and defaults are untouched
  expect(target(out, '{0caa0dad-35be-5f56-a8ff-afceeeaa6101}').members.map(m => m.key)).toEqual(['guid', 'name', 'hidden'])
  expect(target(out).members).toEqual([])
  // GUIDs match without braces and in any case
  expect(setProfileKeys(SRC, GUID.slice(1, -1).toUpperCase(), { backgroundImage: 'x' })).toBe(setProfileKeys(SRC, GUID, { backgroundImage: 'x' }))
})

test('replaces in place, then removes back to the original text', async () => {
  const once = setProfileKeys(SRC, GUID, { backgroundImage: 'a.gif', backgroundImageOpacity: 0.5, backgroundImageStretchMode: 'uniformToFill' })!
  const twice = setProfileKeys(once, GUID, { backgroundImage: 'b.gif', backgroundImageOpacity: 0.3 })!
  expect(readKeys(target(twice, GUID), ['backgroundImage', 'backgroundImageOpacity'])).toEqual({ backgroundImage: 'b.gif', backgroundImageOpacity: 0.3 })
  expect(twice.length).toBe(once.length) // a value swap changes nothing around it
  const restored = setProfileKeys(twice, GUID, { backgroundImage: undefined, backgroundImageOpacity: undefined, backgroundImageStretchMode: undefined })
  expect(restored).toBe(SRC)
})

test('falls back to profiles.defaults, fills an empty object, and empties it again', async () => {
  const out = setProfileKeys(SRC, undefined, { backgroundImage: 'a.gif' })!
  expect(readKeys(target(out), ['backgroundImage'])).toEqual({ backgroundImage: 'a.gif' })
  expect(() => parse(out)).not.toThrow()
  const back = setProfileKeys(out, undefined, { backgroundImage: undefined })!
  expect(target(back).members).toEqual([])
  expect(() => parse(back)).not.toThrow()
})

test('removes a key from the middle and from the end without leaving a stray comma', async () => {
  const src = '{"profiles":{"defaults":{"a":1,"backgroundImage":"x","b":2,"backgroundImageOpacity":0.3}}}'
  const out = setProfileKeys(src, undefined, { backgroundImage: undefined, backgroundImageOpacity: undefined })!
  expect(JSON.parse(out)).toEqual({ profiles: { defaults: { a: 1, b: 2 } } })
})

test('leaves a file it cannot parse, or one with no profile to edit, alone', async () => {
  expect(setProfileKeys('{ "profiles": ', GUID, { backgroundImage: 'a' })).toBeNull()
  expect(setProfileKeys('{ "theme": "dark" }', GUID, { backgroundImage: 'a' })).toBeNull()
})

test('reads the legacy layout where profiles is the list itself', async () => {
  const legacy = `{ "profiles": [ { "guid": "${GUID}", "name": "PS" } ] }`
  const out = setProfileKeys(legacy, GUID, { backgroundImage: 'a.gif' })!
  expect(JSON.parse(out).profiles[0].backgroundImage).toBe('a.gif')
})

test('adds a profile in the list style of the file, once', async () => {
  const entry = { guid: '{d909991b-4fa0-42d3-955b-720d7342c425}', name: 'Claude Code', hidden: false }
  const out = addProfile(SRC, entry)!
  expect(out).toContain('// Make changes here to the powershell.exe profile.')
  const root = parse(out)
  expect(readKeys(listProfile(root, entry.guid)!, ['name', 'hidden'])).toEqual({ name: 'Claude Code', hidden: false })
  expect(out).toContain('            {\n                "guid": "{d909991b')
  expect(addProfile(out, entry)).toBe(out)
  expect(addProfile('{ "profiles": { "defaults": {} } }', entry)).toBeNull()
  expect(JSON.parse(addProfile('{ "profiles": { "list": [] } }', entry)!).profiles.list[0].name).toBe('Claude Code')
})

test('a guid that is not in the list never falls back to defaults', async () => {
  expect(setProfileKeys(SRC, '{00000000-0000-0000-0000-000000000000}', { backgroundImage: 'a' })).toBeNull()
})
